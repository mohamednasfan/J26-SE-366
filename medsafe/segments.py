"""Conservative text crop proposals for existing word-trained TrOCR.

OpenCV proposals are geometry-only. They are not a trained YOLO detector, do not
identify medicines, and cannot establish complete OCR coverage. Large contours
are broken into overlapping review tiles instead of crushing multiple rows into
one 384px crop. Every fallback tile is explicitly marked as uncertain.
"""
from __future__ import annotations
from PIL import Image, ImageOps


def propose_text_regions(image: Image.Image, *, maximum: int = 384):
    try:
        import cv2
        import numpy as np
    except ImportError as exc:
        raise RuntimeError('OpenCV and numpy required for text proposals.') from exc
    im=image.convert('RGB')
    gray=np.asarray(ImageOps.autocontrast(ImageOps.grayscale(im)))
    h,w=gray.shape
    if h<32 or w<64:
        return [], []
    # Adaptive threshold limits the false foreground generated by dark scanned
    # backgrounds and uneven lighting. Remove long straight ruling lines.
    block=41 if min(w,h)>=41 else (min(w,h)//2*2+1)
    ink=cv2.adaptiveThreshold(gray,255,cv2.ADAPTIVE_THRESH_GAUSSIAN_C,
                              cv2.THRESH_BINARY_INV,block,17)
    long_line=cv2.morphologyEx(ink,cv2.MORPH_OPEN,
                              cv2.getStructuringElement(cv2.MORPH_RECT,(max(80,w//5),1)))
    ink=cv2.subtract(ink,long_line)
    near=cv2.morphologyEx(ink,cv2.MORPH_CLOSE,
                         cv2.getStructuringElement(cv2.MORPH_RECT,(max(7,min(15,w//75)),2)))
    contours,_=cv2.findContours(near,cv2.RETR_EXTERNAL,cv2.CHAIN_APPROX_SIMPLE)
    collected=[]
    def push(x1,y1,x2,y2,kind):
        x1=max(0,int(x1)); y1=max(0,int(y1));x2=min(w,int(x2)); y2=min(h,int(y2))
        if x2-x1>=12 and y2-y1>=8:
            collected.append((x1,y1,x2,y2,kind))
    pad_x=max(3,round(.007*w));pad_y=max(3,round(.005*h))
    for ctr in contours:
        x,y,bw,bh=cv2.boundingRect(ctr)
        if bw<max(14,w//130) or bh<max(8,h//210) or bw*bh<75:
            continue
        if bw>=0.72*w and bh>=0.16*h or bh>=0.23*h:
            # One contour may contain several medications. Dividing it into
            # bounded horizontal and vertical tiles avoids severe image resize.
            # Tiles overlap so ink on their boundaries is not silently lost.
            # The review flag prevents claims of complete coverage.
            max_tile_h=max(28,min(54,h//8))
            max_tile_w=max(120,min(290,w//2))
            y_end=y+bh
            yy=y
            while yy<y_end:
                yy2=min(y_end,yy+max_tile_h)
                xx=x
                while xx<x+bw:
                    xx2=min(x+bw,xx+max_tile_w)
                    content=ink[max(0,yy-3):min(h,yy2+3),max(0,xx-4):min(w,xx2+4)]
                    if content.size and int((content>0).sum())>=28:
                        push(xx-5,yy-5,xx2+5,yy2+5,'REVIEW_TILE_FROM_MERGED_CONTOUR')
                    if xx2>=x+bw:break
                    xx=xx2-8
                if yy2>=y_end:break
                yy=yy2-6
        else:
            push(x-pad_x,y-pad_y,x+bw+pad_x,y+bh+pad_y,'ADAPTIVE_CONTOUR')
    # Stable reading-order proposal; individual boxes can still overlap.
    collected=list(dict.fromkeys(collected))
    collected.sort(key=lambda b:(b[1]//max(10,h//80),b[0],b[1],b[2]))
    if len(collected)>maximum:
        raise RuntimeError(f'{len(collected)} text proposals exceed {maximum}; request manual crop review, no truncation.')
    regions=[im.crop((x1,y1,x2,y2)) for x1,y1,x2,y2,_ in collected]
    boxes=[{'x1':x1,'y1':y1,'x2':x2,'y2':y2,'proposal_kind':kind,
            'geometry_verified':False} for x1,y1,x2,y2,kind in collected]
    return regions,boxes
