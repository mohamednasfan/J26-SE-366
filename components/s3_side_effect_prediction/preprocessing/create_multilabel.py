import pandas as pd
import numpy as np
import json

print("Libraries imported successfully!")

from google.colab import files

uploaded = files.upload()

file_path = "/content/twosides_cleaned.csv"

df = pd.read_csv(file_path)

print("Dataset loaded successfully!")
print("Shape:", df.shape)

df.head()

print(df["positive_signal"].value_counts())

print("\nPositive:")
print((df["positive_signal"] == 1).sum())

print("\nNon-positive:")
print((df["positive_signal"] == 0).sum())

positive_df = df[
    df["positive_signal"] == 1
].copy()

side_effect_frequency = (
    positive_df
    .groupby([
        "condition_meddra_id",
        "side_effect"
    ])
    .size()
    .reset_index(name="frequency")
    .sort_values(
        "frequency",
        ascending=False
    )
)

display(side_effect_frequency.head(20))

TOP_N = 800

top_side_effects = (
    side_effect_frequency
    .head(TOP_N)
    .copy()
)

print(
    "Selected side effects:",
    len(top_side_effects)
)

display(top_side_effects.head(10))

top_side_effects = (
    top_side_effects
    .reset_index(drop=True)
)

top_side_effects["label_index"] = (
    top_side_effects.index
)

display(
    top_side_effects[
        [
            "label_index",
            "condition_meddra_id",
            "side_effect",
            "frequency"
        ]
    ].head(20)
)

side_effect_vocabulary = {}

for _, row in top_side_effects.iterrows():

    meddra_id = str(
        int(row["condition_meddra_id"])
    )

    side_effect_vocabulary[meddra_id] = {
        "index": int(row["label_index"]),
        "name": row["side_effect"],
        "frequency": int(row["frequency"])
    }

with open(
    "/content/side_effect_vocabulary.json",
    "w"
) as file:

    json.dump(
        side_effect_vocabulary,
        file,
        indent=4
    )

print("Vocabulary saved!")

selected_ids = set(
    top_side_effects[
        "condition_meddra_id"
    ].tolist()
)

filtered_df = df[
    df["condition_meddra_id"]
    .isin(selected_ids)
].copy()

print("Before:", len(df))
print("After :", len(filtered_df))

resolved_df = (
    filtered_df
    .groupby(
        [
            "drug_1_rxnorm_id",
            "drug_2_rxnorm_id",
            "condition_meddra_id"
        ],
        as_index=False
    )
    .agg(
        positive_signal=(
            "positive_signal",
            "max"
        ),

        max_score=(
            "score",
            "max"
        ),

        total_A=(
            "A",
            "sum"
        )
    )
)

print(
    "Before resolving repeated evidence:",
    len(filtered_df)
)

print(
    "After resolving repeated evidence:",
    len(resolved_df)
)

resolved_df.head()

meddra_to_index = dict(
    zip(
        top_side_effects[
            "condition_meddra_id"
        ],
        top_side_effects[
            "label_index"
        ]
    )
)

resolved_df["label_index"] = (
    resolved_df[
        "condition_meddra_id"
    ].map(meddra_to_index)
)

resolved_df.head()

unique_pairs = (
    resolved_df[
        [
            "drug_1_rxnorm_id",
            "drug_2_rxnorm_id"
        ]
    ]
    .drop_duplicates()
    .reset_index(drop=True)
)

print(
    "Unique drug pairs:",
    len(unique_pairs)
)

NUM_LABELS = TOP_N

label_matrix = np.zeros(
    (
        len(unique_pairs),
        NUM_LABELS
    ),
    dtype=np.uint8
)

print(
    "Label matrix shape:",
    label_matrix.shape
)

pair_to_index = {
    (
        row["drug_1_rxnorm_id"],
        row["drug_2_rxnorm_id"]
    ): index

    for index, row
    in unique_pairs.iterrows()
}

for row in resolved_df.itertuples():

    if row.positive_signal == 1:

        pair = (
            row.drug_1_rxnorm_id,
            row.drug_2_rxnorm_id
        )

        pair_index = pair_to_index[pair]

        label_index = int(
            row.label_index
        )

        label_matrix[
            pair_index,
            label_index
        ] = 1

labels_per_pair = (
    label_matrix.sum(axis=1)
)

print(
    "Minimum positive labels:",
    labels_per_pair.min()
)

print(
    "Maximum positive labels:",
    labels_per_pair.max()
)

print(
    "Average positive labels:",
    labels_per_pair.mean()
)

print(
    "Pairs with no positive labels:",
    (labels_per_pair == 0).sum()
)

valid_mask = (
    labels_per_pair > 0
)

unique_pairs = (
    unique_pairs[
        valid_mask
    ]
    .reset_index(drop=True)
)

label_matrix = (
    label_matrix[
        valid_mask
    ]
)

print(
    "Final drug pairs:",
    len(unique_pairs)
)

print(
    "Final label matrix:",
    label_matrix.shape
)

unique_pairs.to_csv(
    "/content/drug_pairs.csv",
    index=False
)

print("Drug pairs saved!")

np.save(
    "/content/label_matrix.npy",
    label_matrix
)

print("Label matrix saved!")

resolved_df.to_csv(
    "/content/resolved_evidence.csv",
    index=False
)

print("Resolved evidence saved!")

print("===== STAGE 3 SUMMARY =====")

print(
    "Selected side effects:",
    TOP_N
)

print(
    "Unique drug pairs:",
    len(unique_pairs)
)

print(
    "Label matrix shape:",
    label_matrix.shape
)

print(
    "Total positive labels:",
    int(label_matrix.sum())
)

print(
    "Average labels per pair:",
    round(
        label_matrix.sum(axis=1).mean(),
        2
    )
)

print(
    "Maximum labels for one pair:",
    int(
        label_matrix.sum(axis=1).max()
    )
)

print(
    "Pairs with zero labels:",
    int(
        (
            label_matrix.sum(axis=1) == 0
        ).sum()
    )
)