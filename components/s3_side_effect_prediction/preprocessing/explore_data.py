df = pd.read_csv("TWOSIDES.csv")

print("Dataset loaded successfully!")

print("Number of rows:", df.shape[0])
print("Number of columns:", df.shape[1])

df.head()

print(df.columns.tolist())

df.dtypes

missing = df.isnull().sum()

print(missing)

missing_percentage = (
    df.isnull().sum() / len(df)
) * 100

missing_table = pd.DataFrame({
    "Missing Count": df.isnull().sum(),
    "Missing Percentage": missing_percentage
})

missing_table

all_drugs = pd.concat([
    df["drug_1_rxnorn_id"],
    df["drug_2_rxnorm_id"]
])

unique_drugs = all_drugs.nunique()

print("Number of unique drugs:", unique_drugs)

unique_side_effects = df["condition_meddra_id"].nunique()

print("Number of unique side effects:", unique_side_effects)

print(
    "Unique side-effect names:",
    df["side_effect"].nunique()
)

top_side_effects = (
    df["side_effect"]
    .value_counts()
    .head(20)
)

top_side_effects

group_counts = (
    df.groupby([
        "drug_1_rxnorn_id",
        "drug_2_rxnorm_id",
        "condition_meddra_id"
    ])
    .size()
    .reset_index(name="record_count")
)

repeated = group_counts[
    group_counts["record_count"] > 1
]

print(
    "Repeated pair + side-effect combinations:",
    len(repeated)
)

repeated.head(10)

if len(repeated) > 0:

    example = repeated.iloc[0]

    example_rows = df[
        (df["drug_1_rxnorn_id"] == example["drug_1_rxnorn_id"]) &
        (df["drug_2_rxnorm_id"] == example["drug_2_rxnorm_id"]) &
        (df["condition_meddra_id"] == example["condition_meddra_id"])
    ]

    display(
        example_rows[
            [
                "drug1",
                "drug2",
                "side_effect",
                "A",
                "PRR",
                "PRR_error"
            ]
        ]
    )

A_numeric = pd.to_numeric(
    df["A"],
    errors="coerce"
)

PRR_numeric = pd.to_numeric(
    df["PRR"],
    errors="coerce"
)

PRR_error_numeric = pd.to_numeric(
    df["PRR_error"],
    errors="coerce"
)

print("A:")
print(A_numeric.describe())

print("\nPRR:")
print(PRR_numeric.describe())

print("\nPRR Error:")
print(PRR_error_numeric.describe())

low_A_count = (A_numeric < 3).sum()

low_A_percentage = (
    low_A_count / len(df)
) * 100

print("Rows with A < 3:", low_A_count)
print(
    "Percentage:",
    round(low_A_percentage, 2),
    "%"
)

import matplotlib.pyplot as plt

plt.figure(figsize=(8, 5))

A_numeric[A_numeric <= 100].hist(
    bins=50
)

plt.title("Distribution of A Counts (A ≤ 100)")
plt.xlabel("A Count")
plt.ylabel("Number of Records")

plt.show()

summary = {
    "Total rows": len(df),
    "Total columns": len(df.columns),
    "Unique drugs": all_drugs.nunique(),
    "Unique MedDRA side effects":
        df["condition_meddra_id"].nunique(),
    "Unique side-effect names":
        df["side_effect"].nunique(),
    "Rows with A < 3":
        int((A_numeric < 3).sum()),
    "Invalid A values":
        int(A_numeric.isna().sum()),
    "Invalid PRR values":
        int(PRR_numeric.isna().sum()),
    "Invalid PRR_error values":
        int(PRR_error_numeric.isna().sum())
}

for key, value in summary.items():
    print(f"{key}: {value}")