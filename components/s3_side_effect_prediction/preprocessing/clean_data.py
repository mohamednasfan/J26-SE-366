import pandas as pd
import numpy as np

print("Libraries imported successfully!")

from google.colab import files

uploaded = files.upload()

file_path = "/content/TWOSIDES.csv"

df = pd.read_csv(
    file_path,
    low_memory=False
)

print("Dataset loaded!")
print("Original shape:", df.shape)

df.head()

df.rename(
    columns={
        "drug_1_rxnorn_id": "drug_1_rxnorm_id"
    },
    inplace=True
)

print(df.columns.tolist())

numeric_columns = [
    "drug_1_rxnorm_id",
    "drug_2_rxnorm_id",
    "condition_meddra_id",
    "A",
    "PRR",
    "PRR_error"
]

for column in numeric_columns:
    df[column] = pd.to_numeric(
        df[column],
        errors="coerce"
    )

print(df[numeric_columns].dtypes)

print("Invalid values before cleaning:\n")

for column in numeric_columns:
    print(
        column,
        ":",
        df[column].isna().sum()
    )



invalid_rows = df[
    df[numeric_columns].isna().any(axis=1)
]

print("Invalid rows:", len(invalid_rows))

display(invalid_rows)

before = len(df)

df = df.dropna(
    subset=numeric_columns
).copy()

after = len(df)

print("Before:", before)
print("After :", after)
print("Removed:", before - after)

invalid_prr = (df["PRR"] <= 0).sum()

print("PRR <= 0:", invalid_prr)

display(
    df[df["PRR"] <= 0][
        [
            "drug1",
            "drug2",
            "side_effect",
            "A",
            "PRR",
            "PRR_error"
        ]
    ].head(20)
)

df["score"] = (
    np.log(df["PRR"])
    - 1.96 * df["PRR_error"]
)

display(
    df[
        [
            "drug1",
            "drug2",
            "side_effect",
            "A",
            "PRR",
            "PRR_error",
            "score"
        ]
    ].head(10)
)

print(df["score"].describe())

positive_count = (df["score"] >= 0).sum()
non_positive_count = (df["score"] < 0).sum()

print("Score >= 0 :", positive_count)
print("Score < 0:", non_positive_count)

print(
    "Positive percentage:",
    round(
        positive_count / len(df) * 100,
        2
    ),
    "%"
)

print(
    "NaN scores:",
    df["score"].isna().sum()
)

print(
    "Infinite scores:",
    np.isinf(df["score"]).sum()
)

before = len(df)

df = df[
    df["score"].notna()
    & np.isfinite(df["score"])
].copy()

print(
    "Invalid score rows removed:",
    before - len(df)
)

A_THRESHOLD = 3

before = len(df)

df = df[
    df["A"] >= A_THRESHOLD
].copy()

after = len(df)

print("A threshold:", A_THRESHOLD)
print("Before:", before)
print("After :", after)
print("Removed:", before - after)

swap_mask = (
    df["drug_1_rxnorm_id"]
    > df["drug_2_rxnorm_id"]
)

print(
    "Pairs requiring swapping:",
    swap_mask.sum()
)

drug1_id = df.loc[
    swap_mask,
    "drug_1_rxnorm_id"
].copy()

drug1_name = df.loc[
    swap_mask,
    "drug1"
].copy()


df.loc[
    swap_mask,
    "drug_1_rxnorm_id"
] = df.loc[
    swap_mask,
    "drug_2_rxnorm_id"
].values

df.loc[
    swap_mask,
    "drug1"
] = df.loc[
    swap_mask,
    "drug2"
].values


df.loc[
    swap_mask,
    "drug_2_rxnorm_id"
] = drug1_id.values

df.loc[
    swap_mask,
    "drug2"
] = drug1_name.values

wrong_order = (
    df["drug_1_rxnorm_id"]
    > df["drug_2_rxnorm_id"]
).sum()

print(
    "Incorrectly ordered pairs:",
    wrong_order
)

group_counts = (
    df.groupby(
        [
            "drug_1_rxnorm_id",
            "drug_2_rxnorm_id",
            "condition_meddra_id"
        ]
    )
    .size()
    .reset_index(
        name="record_count"
    )
)

repeated = group_counts[
    group_counts["record_count"] > 1
]

print(
    "Repeated pair + side-effect combinations:",
    len(repeated)
)

df["positive_signal"] = (
    df["score"] > 0
).astype(int)

print(
    df["positive_signal"]
    .value_counts()
)

columns_to_keep = [
    "drug_1_rxnorm_id",
    "drug1",
    "drug_2_rxnorm_id",
    "drug2",
    "condition_meddra_id",
    "side_effect",
    "A",
    "PRR",
    "PRR_error",
    "score",
    "positive_signal"
]

clean_df = df[
    columns_to_keep
].copy()

clean_df.head()

print("Final rows:", len(clean_df))
print("Final columns:", len(clean_df.columns))

print(
    "Unique drugs:",
    pd.concat(
        [
            clean_df["drug_1_rxnorm_id"],
            clean_df["drug_2_rxnorm_id"]
        ]
    ).nunique()
)

print(
    "Unique side effects:",
    clean_df[
        "condition_meddra_id"
    ].nunique()
)

print(
    "Positive signals:",
    clean_df[
        "positive_signal"
    ].sum()
)

print(
    "Missing values:",
    clean_df.isna().sum().sum()
)

print(
    "Infinite scores:",
    np.isinf(
        clean_df["score"]
    ).sum()
)

output_path = "/content/twosides_cleaned.csv"

clean_df.to_csv(
    output_path,
    index=False
)

print(
    "Saved successfully:",
    output_path
)